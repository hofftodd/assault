export const FONT_CELL_W = 6;
export const FONT_CELL_H = 8;
export const FONT_CHARS = Object.keys(GLYPHS).join('');
export const FONT_COLUMNS = 16;

/** White glyphs on transparent, laid out FONT_COLUMNS per row (for Phaser's RetroFont). */
export function rasterizeFont(): { width: number; height: number; data: Uint8ClampedArray } {
  const chars = [...FONT_CHARS];
  const width = FONT_COLUMNS * FONT_CELL_W;
  const height = Math.ceil(chars.length / FONT_COLUMNS) * FONT_CELL_H;
  const data = new Uint8ClampedArray(width * height * 4);
  chars.forEach((ch, n) => {
    const ox = (n % FONT_COLUMNS) * FONT_CELL_W;
    const oy = Math.floor(n / FONT_COLUMNS) * FONT_CELL_H;
    GLYPHS[ch].split(' ').forEach((row, y) => {
      [...row].forEach((px, x) => {
        if (px !== '#') return;
        data.fill(255, ((oy + y) * width + ox + x) * 4, ((oy + y) * width + ox + x) * 4 + 4);
      });
    });
  });
  return { width, height, data };
}
